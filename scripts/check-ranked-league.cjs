const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
function compile(file, globals = {}, requireMock = require) {
  const module = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  vm.runInNewContext('(function(require,module,exports){' + code + '})', { ...globals })(requireMock, module, module.exports);
  return module.exports;
}
async function main() {
  const { rankedLeagueStats } = compile('src/utils/rankedLeagueStats.ts');
  const member = { playerTag: '#ABC', leagueTrophies: 250, attackWinCount: 0, attackLoseCount: 2, defenseWinCount: 1, defenseLoseCount: 3 };
  const group = { members: [{ playerTag: '#TOP', leagueTrophies: 400 }, member, { playerTag: '#TIE', leagueTrophies: 250 }, { playerTag: '#LOW', leagueTrophies: 100 }] };
  const result = rankedLeagueStats(group, 'abc');
  assert.equal(result.trophies, 250);
  assert.equal(result.position, 2);
  assert.equal(result.tied, true);
  assert.equal(result.positionIsOfficial, false, 'Trophy comparisons cannot claim to be official tie-broken ranks');
  assert.equal(result.attackWins, 0, 'Genuine zero wins remain zero');
  assert.equal(result.attackLosses, 2);
  assert.equal(result.defenseWins, 1);
  assert.equal(result.defenseLosses, 3);
  assert.equal(rankedLeagueStats(group, '#MISSING'), null);
  const absent = rankedLeagueStats({ members: [{ playerTag: '#ABC' }] }, '#ABC');
  assert.equal(absent.trophies, null);
  assert.equal(absent.position, null);
  assert.equal(absent.attackWins, null, 'Missing stats never fall back to fabricated zeros');
  const explicit = rankedLeagueStats({ members: [{ ...member, rank: 3 }] }, '#ABC');
  assert.equal(explicit.position, 3);
  assert.equal(explicit.positionIsOfficial, true);
  assert.equal(rankedLeagueStats({ members: [member, { playerTag: '#UNKNOWN' }] }, '#ABC').position, null);
  const { tournamentStandings, nearbyStandings } = compile('src/utils/rankedTournamentView.ts');
  const standings = tournamentStandings(result, 'abc', 8, { min: 2, max: 2 }, null);
  assert.equal(standings[1].self, true);
  assert.equal(standings[1].position, 2);
  assert.equal(standings[1].zone, 'uncertain', 'A tie crossing the cutoff cannot claim promotion');
  assert.equal(standings[1].attacksLeft, 6);
  assert.equal(standings[0].attacksLeft, null, 'Absent counters are not zero completed battles');
  const incompleteScores = tournamentStandings({ ...result, members: [member, { playerTag: '#UNKNOWN' }] }, 'abc', 8, null, null);
  assert.equal(incompleteScores[0].position, null, 'Unknown group scores cannot imply a known place');
  const officialRows = tournamentStandings({ ...result, members: [{ ...member, rank: 2 }, { playerTag: '#TOP', leagueTrophies: 100, rank: 1 }] }, 'abc', 8, null, null);
  assert.equal(officialRows[0].member.playerTag, '#TOP', 'Official rank takes priority over raw score');
  const many = tournamentStandings({ ...result, members: Array.from({ length: 30 }, (_, i) => ({ playerTag: '#P' + i, leagueTrophies: 1000 - i })) }, '#P20', 8, { min: 10, max: 15 }, null);
  const nearby = nearbyStandings(many, { min: 10, max: 15 });
  for (const index of [0, 9, 14, 18, 19, 20, 21, 22]) assert.ok(nearby.some(row => row.index === index));
  assert.ok(nearby.length < many.length);
  const { getRankedProjectionRules } = compile('src/utils/rankedLeagueRules.ts');
  const { projectRankedLeague } = compile('src/utils/rankedLeagueProjection.ts');
  assert.equal(getRankedProjectionRules('Titan 25').battles, 12, 'Do not use the old package count of 14');
  assert.equal(getRankedProjectionRules('Dragon 28').battles, 14);
  assert.equal(getRankedProjectionRules('Electro 31').battles, 18);
  assert.equal(getRankedProjectionRules('Legend III').fixedPromotionSlots, 5);
  assert.equal(getRankedProjectionRules('Legend II').battles, 30);
  assert.equal(getRankedProjectionRules('Legend I').mode, 'legend-daily');
  assert.equal(getRankedProjectionRules('Unknown League'), null);
  const leagueData = compile('src/utils/leagueData.ts', {}, id => id === './rankedLeagueRules' ? { getRankedProjectionRules } : require(id));
  assert.equal(leagueData.getLeagueLootInfo('Titan 25', 18).attacksPerWeek, 12, 'The League card uses the corrected attack limit too');
  assert.equal(leagueData.getLeagueLootInfo('Titan 25', 18).floor, 'Titan 26', 'Use the updated TH18 floor');
  const weekly = getRankedProjectionRules('Archer 8');
  const self = { playerTag: '#SELF', leagueTrophies: 110, attackWinCount: 2, attackLoseCount: 0, defenseWinCount: 0, defenseLoseCount: 4 };
  const others = Array.from({ length: 19 }, (_, i) => ({ playerTag: '#P' + i, leagueTrophies: 200 - i * 5, attackWinCount: 4, attackLoseCount: 0, defenseWinCount: 0, defenseLoseCount: 2 }));
  const rawGroup = { members: [self, ...others], attackLogs: [{ trophies: 40 }, { trophies: 30 }], defenseLogs: Array.from({ length: 4 }, () => ({ trophies: 10 })) };
  const normalized = rankedLeagueStats(rawGroup, '#SELF');
  const forecast = projectRankedLeague(normalized, weekly, '#SELF');
  assert.equal(forecast.attacksLeft, 6);
  assert.equal(forecast.defensesLeft, 4);
  assert.equal(forecast.attackAverage, 35);
  assert.equal(forecast.defenseAverage, 10);
  assert.equal(forecast.expectedDefenseGain, 40, 'Four remaining defenses at a +10 average add an estimated +40');
  assert.equal(forecast.projectedTotal, 360);
  assert.equal(forecast.threeStarTotal, 390);
  assert.equal(forecast.maximumTotal, 510);
  const { rankedMatchupScenario } = compile('src/utils/rankedMatchupScenario.ts');
  const tough = rankedMatchupScenario(forecast, normalized.trophies, 2, 20);
  assert.equal(tough.attackGain, 180, 'Four normal attacks at 35 plus two tough attacks at 20');
  assert.equal(tough.total, 330, 'Include current score and unchanged defense fill');
  assert.equal(tough.average, 30);
  assert.equal(rankedMatchupScenario({ ...forecast, attackAverage: 40 }, 110, 2, 20).attackGain, 200, 'A perfect early sample still allows for two tough matchups');
  assert.equal(rankedMatchupScenario({ ...forecast, attacksLeft: 1 }, 110, 2, 20).attackGain, 20, 'A nearly finished tournament caps tough attacks at one');
  assert.equal(rankedMatchupScenario(forecast, 110, 0, 20).total, forecast.projectedTotal);
  assert.equal(rankedMatchupScenario(forecast, 110, 20, 20).toughAttacks, 6, 'Never replace more attacks than remain');
  assert.equal(rankedMatchupScenario({ ...forecast, attackAverage: 10 }, 110, 2, 20).attackGain, 60, 'Tough matchups cannot boost a low observed average');
  assert.equal(rankedMatchupScenario({ ...forecast, attackAverage: null }, 110, 2, 20).total, null);
  assert.equal(rankedMatchupScenario({ ...forecast, expectedDefenseGain: null }, 110, 2, 20).total, null);
  assert.equal(rankedMatchupScenario({ ...forecast, attacksLeft: 0, attackAverage: null }, 110, 2, 20).total, 150);
  assert.equal(rankedMatchupScenario(forecast, 110, 2, 41), null);
  assert.equal(rankedMatchupScenario({ ...forecast, supported: false }, 110, 2, 20), null);
  assert.equal(forecast.promotionSlots.min, 8);
  assert.equal(forecast.promotionSlots.max, 10, 'Published percentage ranges stay ranges');
  assert.equal(forecast.cutoff.min, 155);
  assert.equal(forecast.cutoff.max, 165);
  assert.equal(forecast.triplesToClear, 1);
  assert.equal(forecast.trophiesToClear, 56, 'Beating the cutoff requires one point beyond ties');
  assert.equal(forecast.outlook, 'open');
  const missing = projectRankedLeague({ ...normalized, defenseLogs: [] }, weekly, '#SELF');
  assert.equal(missing.expectedDefenseGain, null, 'Do not average a partial log');
  const alreadyFilled = projectRankedLeague({ ...normalized, trophies: 150 }, weekly, '#SELF');
  assert.equal(alreadyFilled.expectedDefenseGain, null, 'Avoid double-counting unlogged or already-filled defense points');
  assert.equal(projectRankedLeague({ ...normalized, defenseLogs: [{ trophies: -10 }] }, weekly, '#SELF').supported, false);
  assert.equal(projectRankedLeague(normalized, getRankedProjectionRules('Legend I'), '#SELF').supported, false);
  const completeMembers = [self, ...others].map(member => ({ ...member, leagueTrophies: member.playerTag === '#SELF' ? 600 : 0, attackWinCount: 8, attackLoseCount: 0, defenseWinCount: 0, defenseLoseCount: 8 }));
  const secured = rankedLeagueStats({ members: completeMembers, attackLogs: Array.from({ length: 8 }, () => ({ trophies: 40 })), defenseLogs: Array.from({ length: 8 }, () => ({ trophies: 35 })) }, '#SELF');
  assert.equal(projectRankedLeague(secured, weekly, '#SELF').outlook, 'secured');
  const eliminated = rankedLeagueStats({ members: completeMembers.map(member => ({ ...member, leagueTrophies: member.playerTag === '#SELF' ? 0 : 100 })), attackLogs: Array.from({ length: 8 }, () => ({ trophies: 0 })), defenseLogs: Array.from({ length: 8 }, () => ({ trophies: 0 })) }, '#SELF');
  assert.equal(projectRankedLeague(eliminated, weekly, '#SELF').outlook, 'out-of-reach');
  const tiedScores = { ...secured, trophies: 0, members: completeMembers.map(member => ({ ...member, leagueTrophies: 0 })) };
  assert.equal(projectRankedLeague(tiedScores, weekly, '#SELF').outlook, 'open', 'Ties cannot be called guaranteed promotion');
  const noPeerCounters = { ...normalized, members: normalized.members.map(member => member.playerTag === '#SELF' ? member : { playerTag: member.playerTag, leagueTrophies: member.leagueTrophies }) };
  assert.equal(projectRankedLeague(noPeerCounters, weekly, '#SELF').worstPlace, null);
  const noDefenseSample = rankedLeagueStats({ members: [{ ...self, leagueTrophies: 70, defenseWinCount: 0, defenseLoseCount: 0 }, ...others], attackLogs: rawGroup.attackLogs, defenseLogs: [] }, '#SELF');
  assert.equal(projectRankedLeague(noDefenseSample, weekly, '#SELF').defenseAverage, null);
  assert.equal(projectRankedLeague(noDefenseSample, weekly, '#SELF').expectedDefenseGain, null);
  let request;
  const globals = { AbortController, setTimeout, clearTimeout, fetch: async (url, options) => { request = { url, options }; return { ok: true, json: async () => group }; } };
  const { ClashAPI } = compile('src/api/clash.ts', globals);
  const response = await new ClashAPI('test-token').getPlayerLeagueGroup('#GROUP', 202611, '#ABC');
  assert.equal(response, group);
  assert.equal(request.url, 'https://cocproxy.royaleapi.dev/v1/leaguegroup/%23GROUP/202611?playerTag=%23ABC');
  assert.equal(request.options.headers.Authorization, 'Bearer test-token');
  globals.fetch = async () => ({ ok: false, status: 404, json: async () => ({ reason: 'notFound' }) });
  const failing = compile('src/api/clash.ts', globals);
  await assert.rejects(() => new failing.ClashAPI('test-token').getPlayerLeagueGroup('#GROUP', 202611, '#ABC'), error => error.status === 404);
  console.log('Ranked league regression checks passed.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
