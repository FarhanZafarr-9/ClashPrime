import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
// Generate from the same bundled data used by army progress and artwork.
const entities = {};
for (const village of ['home', 'builder']) {
  for (const folder of ['heroes', 'troops', 'spells', 'pets']) {
    const dir = join('node_modules/clash-of-clans-data/data', village, folder);
    let files;
    try { files = readdirSync(dir); } catch { continue; }
    for (const file of files.filter(f => f.endsWith('.json'))) {
      const item = JSON.parse(readFileSync(join(dir, file), 'utf8'));
      if (Number.isFinite(item.dataId)) entities[item.dataId] = { name: item.name, kind: folder, village: village === 'builder' ? 'builderBase' : 'home' };
    }
  }
}
writeFileSync('src/data/cocUnitIds.ts', '// Generated by scripts/gen-coc-unit-ids.mjs.\nexport const COC_UNIT_IDS: Record<number, { name: string; kind: \'heroes\' | \'troops\' | \'spells\' | \'pets\'; village: \'home\' | \'builderBase\' }> = '+JSON.stringify(entities,null,2)+';\n');
